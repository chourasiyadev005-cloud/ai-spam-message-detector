from pathlib import Path
import json
import joblib
import streamlit as st
import pandas as pd

ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT / "spam_model.joblib"
METRICS_PATH = ROOT / "model_metrics.json"

st.set_page_config(page_title="AI Spam Message Detector", page_icon="📩", layout="wide")

st.title("📩 AI Spam Message Detector")
st.caption("Machine learning classification using TF-IDF and a trained scikit-learn model.")

if not MODEL_PATH.exists() or not METRICS_PATH.exists():
    st.warning("The model is not trained yet. Open the project terminal and run: python train_model.py")
    st.stop()

@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)

model = load_model()
metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))

st.info("Dataset note: the supplied dataset contains SMS messages. This demo can classify pasted text, but its measured performance is based on SMS data—not a dedicated email dataset.")

tab_detect, tab_metrics, tab_about = st.tabs(["🔎 Detect message", "📊 Model evaluation", "ℹ️ How it works"])

with tab_detect:
    st.subheader("Check a message")
    message = st.text_area(
        "Paste message text",
        height=200,
        placeholder="Example: Congratulations! You have won a prize. Call now to claim..."
    )
    if st.button("Analyze message", type="primary", use_container_width=True):
        if not message.strip():
            st.error("Please paste a message first.")
        else:
            prediction = model.predict([message])[0]
            if hasattr(model, "predict_proba"):
                probs = model.predict_proba([message])[0]
                classes = list(model.classes_)
                score_map = {str(c): float(p) for c, p in zip(classes, probs)}
                spam_score = score_map.get("spam", 0.0)
            else:
                spam_score = None

            if prediction == "spam":
                st.error("🚨 Prediction: SPAM")
            else:
                st.success("✅ Prediction: HAM (likely legitimate)")

            if spam_score is not None:
                st.metric("Estimated spam score", f"{spam_score:.1%}")
                st.progress(spam_score, text="Model-estimated spam probability")
                st.caption("This score is a model estimate, not a guarantee or a security verdict.")

            warning_terms = [
                "verify your account", "password", "click here", "claim your prize",
                "bank details", "urgent", "limited time", "winner", "act now",
                "gift card", "one-time password", "otp"
            ]
            found = [term for term in warning_terms if term in message.lower()]
            if found:
                st.write("Potentially suspicious wording:")
                st.write(", ".join(f"`{term}`" for term in found))
            st.warning("Do not click links, open attachments, or share passwords/OTPs based only on this prediction.")

with tab_metrics:
    st.subheader("Held-out test-set results")
    st.caption(f"Selected model: {metrics['best_model']}. Metrics are generated by train_model.py from a stratified test split.")
    best = metrics["models"][metrics["best_model"]]
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Accuracy", f"{best['accuracy']:.1%}")
    c2.metric("Spam precision", f"{best['precision_spam']:.1%}")
    c3.metric("Spam recall", f"{best['recall_spam']:.1%}")
    c4.metric("Spam F1-score", f"{best['f1_spam']:.1%}")

    comparison = pd.DataFrame(metrics["models"]).T.rename(columns={
        "accuracy": "Accuracy",
        "precision_spam": "Spam precision",
        "recall_spam": "Spam recall",
        "f1_spam": "Spam F1-score"
    })
    st.markdown("**Model comparison**")
    st.dataframe((comparison * 100).round(2).astype(str) + "%", use_container_width=True)

    cm = metrics["confusion_matrix"]
    cm_df = pd.DataFrame(cm, index=["Actual ham", "Actual spam"], columns=["Predicted ham", "Predicted spam"])
    st.markdown("**Confusion matrix**")
    st.dataframe(cm_df, use_container_width=True)
    st.caption(f"Rows after cleaning and duplicate removal: {metrics['rows_after_cleaning_and_deduplication']:,} · Train: {metrics['train_rows']:,} · Test: {metrics['test_rows']:,}")

with tab_about:
    st.subheader("Project architecture")
    st.markdown("""
    1. **Data cleaning:** remove missing/empty rows and exact duplicate messages.
    2. **Train/test split:** stratified 80/20 split with a fixed random seed.
    3. **TF-IDF:** convert words and two-word phrases into numerical features.
    4. **Model training:** compare Multinomial Naive Bayes and Logistic Regression.
    5. **Model selection:** choose the model with the higher spam-class F1-score.
    6. **Evaluation:** report accuracy, spam precision, spam recall, spam F1-score, and confusion matrix.
    7. **Prediction:** use the trained pipeline to classify new pasted text.
    """)
    st.markdown("**Limitations**")
    st.write("This project is a learning/demo system. The source dataset contains SMS messages, so performance may differ on real email. It does not inspect headers, attachments, URLs, or inbox metadata. Do not treat it as a standalone cybersecurity tool.")
